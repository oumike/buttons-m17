#!/usr/bin/env python3
"""Generate src/config/reflectors_builtin.cpp from data/M17_Hosts.txt.

The host file is Pi-Star's M17_Hosts.txt (tab separated: name, host, port),
built from DVRef data (CC BY 4.0, https://dvref.com/). Refresh it with:

    curl -fsSL -A "buttons-m17/1.0" -o data/M17_Hosts.txt \
        https://www.pistar.uk/downloads/M17_Hosts.txt
    python3 tools/gen_reflectors.py

Changes made to the data: entries whose host is an IPv6 literal are dropped
(the firmware links over IPv4 only); everything else is copied unchanged.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "M17_Hosts.txt"
OUT = ROOT / "src" / "config" / "reflectors_builtin.cpp"

NAME_RE = re.compile(r"^M17-[A-Z0-9]{3}$")
HOST_RE = re.compile(r"^[A-Za-z0-9.-]+$")


def main() -> int:
    generated = ""
    rows, skipped = [], []
    for line in SRC.read_text().splitlines():
        if line.startswith("# Generated:"):
            generated = line.split(":", 1)[1].strip()
        if not line.strip() or line.startswith("#"):
            continue
        name, host, port = line.split("\t")
        if not NAME_RE.match(name):
            sys.exit(f"bad reflector name: {name!r}")
        if not HOST_RE.match(host):
            skipped.append(name)
            continue
        port = int(port)
        if not 0 < port < 65536:
            sys.exit(f"bad port for {name}: {port}")
        rows.append((name, host, port))

    rows.sort()
    body = "\n".join(f'    {{"{n}", "{h}", {p}}},' for n, h, p in rows)
    OUT.write_text(f"""\
// GENERATED by tools/gen_reflectors.py from data/M17_Hosts.txt - do not edit.
//
// Reflector data provided by DVRef - https://dvref.com/ (CC BY 4.0), via the
// Pi-Star host file (snapshot {generated or "unknown"}). Changes: IPv6-only
// entries dropped ({", ".join(skipped) or "none"}).
#include "config/reflectors.h"

namespace cfg {{

const ReflectorEntry BUILTIN_REFLECTORS[] = {{
{body}
}};
const size_t BUILTIN_REFLECTOR_COUNT = sizeof(BUILTIN_REFLECTORS) / sizeof(BUILTIN_REFLECTORS[0]);
const char *const BUILTIN_REFLECTORS_DATE = "{generated}";

}}  // namespace cfg
""")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} reflectors, skipped {skipped}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
